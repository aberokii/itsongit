"""Rebuild the ledger of repos used for content: POSTED_REPOS.md (human) + data/posted.json (scout skip-list).

Sources: every videos/*/post.json (built or posted), plus Zernio posts' metadata.repo when ZERNIO_API_KEY is set
(so a fresh cloud checkout still knows what's already live). Python 3.9+, stdlib only.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "pipeline"))

rows = {}
for pj in sorted((ROOT / "videos").glob("*/post.json")):
    p = json.loads(pj.read_text())
    if not p.get("repo_url"):
        continue
    repo = p["repo_url"].split("github.com/")[-1].strip("/")
    z = p.get("zernio", {})
    rows[repo.lower()] = {"repo": repo, "video": pj.parent.name, "title": p.get("title", ""), "keyword": p.get("keyword", ""),
                          "status": z.get("status") or "built, not scheduled", "when": (z.get("publishedAt") or z.get("scheduledFor") or "")[:16],
                          "url": z.get("url") or ""}

try:
    import zernio as zz  # noqa: E402
    if not zz.DRY:
        page = zz.api("GET", "/posts", query={"platform": "instagram", "limit": 100})
        for post in page.get("posts", []):
            repo = (post.get("metadata") or {}).get("repo", "").split("github.com/")[-1].strip("/")
            if repo and repo.lower() not in rows:
                pl = (post.get("platforms") or [{}])[0]
                rows[repo.lower()] = {"repo": repo, "video": (post.get("metadata") or {}).get("reel", ""), "title": "", "keyword": (post.get("metadata") or {}).get("keyword", ""),
                                      "status": post.get("status", ""), "when": (pl.get("publishedAt") or post.get("scheduledFor") or "")[:16], "url": pl.get("platformPostUrl") or ""}
except SystemExit:
    pass

items = sorted(rows.values(), key=lambda r: r["video"])
(ROOT / "data/posted.json").write_text(json.dumps([r["repo"] for r in items], indent=1))
lines = ["# Repos used for @itsongit content", "",
         "Auto-generated by `pipeline/ledger.py` from `videos/*/post.json` and Zernio. **Never make a second video about a repo listed here.**",
         "The scout (`pipeline/scout.py`) skips these automatically via `data/posted.json`.", "",
         "| # | Repo | Video | Keyword | Status | When (UTC) | Instagram |", "|---|---|---|---|---|---|---|"]
for i, r in enumerate(items, 1):
    lines.append(f"| {i} | [{r['repo']}](https://github.com/{r['repo']}) | {r['video']} | {r['keyword']} | {r['status']} | {r['when']} | {r['url']} |")
(ROOT / "POSTED_REPOS.md").write_text("\n".join(lines) + "\n")
print(f"{len(items)} repos → POSTED_REPOS.md, data/posted.json")
